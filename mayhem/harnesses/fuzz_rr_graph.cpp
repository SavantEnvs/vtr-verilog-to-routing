// Fuzz VTR's routing-resource-graph XML reader (librrgraph load_rr_file: the generated uxsdcxx XML
// loader rr_graph_uxsdcxx.h + RrGraphSerializer, rr_graph_uxsdcxx_serializer.h), the code behind
// `vpr --read_rr_graph <file>.xml`. The device context it validates the file against is set up once,
// read-only, the way vpr does it (vpr/src/base/setup_vpr.cpp setup_switches, rr_graph.cpp
// create_rr_graph): a fixed architecture (k4_N4_90nm, embedded below) and a fixed 4x4 device grid
// (io on the perimeter, clb inside). Every input gets a fresh, empty RR graph.
//
// Built with MAYHEM_RR_SEED_GEN defined, the same file is a tool that writes an RR graph skeleton
// (switches/segments/block_types/grid of that device) with upstream's write_rr_graph, for seeds.
