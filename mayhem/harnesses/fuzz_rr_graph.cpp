namespace {
struct Device {
    t_arch arch;
    std::vector<t_physical_tile_type> tiles;
    std::vector<t_logical_block_type> blocks;
    std::vector<t_arch_switch_inf> arch_switch_inf;
    std::unique_ptr<DeviceGrid> grid;
    std::string arch_path;  // t_arch keeps a pointer to the file name; keep it alive
};
Device* g_dev = nullptr;
std::string g_path;

std::string scratch(const char* suffix) {
    const char* tmp = getenv("TMPDIR");
    std::string tmpl = std::string(tmp && *tmp ? tmp : "/tmp") + "/vtr_rr_XXXXXX" + suffix;
    std::vector<char> buf(tmpl.begin(), tmpl.end());
    buf.push_back('\0');
    int fd = mkstemps(buf.data(), (int)strlen(suffix));
    if (fd < 0) abort();
    close(fd);
    return buf.data();
}

void setup_device() {
    g_dev = new Device;
    g_dev->arch_path = scratch(".xml");
    const std::string& arch_path = g_dev->arch_path;
    FILE* f = fopen(arch_path.c_str(), "wb");
    if (!f) abort();
    fwrite(kArchXml, 1, sizeof(kArchXml) - 1, f);
    fclose(f);
    xml_read_arch(arch_path.c_str(), true, &g_dev->arch, g_dev->tiles, g_dev->blocks, false);
    unlink(arch_path.c_str());

    // arch switches + vpr's delayless switch (setup_vpr.cpp setup_switches)
    g_dev->arch_switch_inf = g_dev->arch.switches;
    t_arch_switch_inf delayless;
    delayless.set_type(e_switch_type::MUX);
    delayless.name = "__vpr_delayless_switch__";
    delayless.R = 0.;
    delayless.Cin = 0.;
    delayless.Cout = 0.;
    delayless.set_Tdel(t_arch_switch_inf::UNDEFINED_FANIN, 0., 0.);
    g_dev->arch_switch_inf.push_back(delayless);

    const t_physical_tile_type* io = nullptr;
    const t_physical_tile_type* clb = nullptr;
    for (const auto& t : g_dev->tiles) {
        if (t.name == "io") io = &t;
        if (t.name == "clb") clb = &t;
    }
    if (!io || !clb) abort();
    const int W = 4, H = 4;
    vtr::NdMatrix<t_grid_tile, 3> tiles({1, (size_t)W, (size_t)H});
    for (int x = 0; x < W; ++x) {
        for (int y = 0; y < H; ++y) {
            bool edge_x = (x == 0 || x == W - 1), edge_y = (y == 0 || y == H - 1);
            const t_physical_tile_type* t = &g_dev->tiles[0];  // EMPTY
            if (edge_x != edge_y) t = io;
            else if (!edge_x && !edge_y) t = clb;
            tiles[0][x][y].type = t;
        }
    }
    g_dev->grid = std::make_unique<DeviceGrid>(g_dev->arch.grid_layouts[0], std::move(tiles));
}

struct Graph {
    RRGraphBuilder builder{};
    vtr::vector<RRIndexedDataId, t_rr_indexed_data> indexed;
    RRRCData rc;
    RRGraphView view{builder.rr_nodes(), builder.node_lookup(), builder.rr_node_metadata(),
                     builder.rr_edge_metadata(), indexed, rc, builder.rr_segments(), builder.rr_switch()};
    t_chan_width chan;
    std::string loaded;
};
}  // namespace

extern "C" int LLVMFuzzerInitialize(int*, char***) {
    vtr::set_log_file(nullptr);
    setup_device();
    g_path = scratch(".xml");  // the reader picks the XML loader by the .xml extension
    return 0;
}

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
    FILE* f = fopen(g_path.c_str(), "wb");
    if (!f) abort();
    fwrite(data, 1, size, f);
    fclose(f);
    auto g = std::make_unique<Graph>();
    try {
        load_rr_file(&g->builder, &g->view, g_dev->tiles, g_dev->arch.Segments, &g->indexed, g->rc,
                     *g_dev->grid, g_dev->arch_switch_inf, e_graph_type::UNIDIR, &g_dev->arch, &g->chan,
                     DELAY_NORMALIZED_LENGTH, g_path.c_str(), &g->loaded,
                     /*read_edge_metadata=*/true, /*do_check_rr_graph=*/true, /*echo_enabled=*/false,
                     /*echo_file_name=*/"", /*route_verbosity=*/0, /*is_flat=*/false,
                     /*device_model_warnings=*/false);
    } catch (vtr::VtrError&) {
    } catch (std::exception&) {
    }
    return 0;
}

#ifdef MAYHEM_RR_SEED_GEN
int main(int argc, char** argv) {
    if (argc != 2) return 2;
    LLVMFuzzerInitialize(&argc, &argv);
    Graph g;
    g.chan.max = g.chan.x_max = g.chan.y_max = g.chan.x_min = g.chan.y_min = 4;
    g.chan.x_list.assign(g_dev->grid->height(), 4);
    g.chan.y_list.assign(g_dev->grid->width(), 4);
    for (const auto& seg : g_dev->arch.Segments) g.builder.add_rr_segment(seg);
    for (const auto& sw : g_dev->arch_switch_inf) {
        t_rr_switch_inf rsw;
        rsw.name = sw.name;
        rsw.set_type(sw.type());
        rsw.R = sw.R; rsw.Cin = sw.Cin; rsw.Cout = sw.Cout; rsw.Tdel_min = sw.Tdel_min(); rsw.Tdel_max = sw.Tdel_max();
        g.builder.add_rr_switch(rsw);
    }
    write_rr_graph(&g.builder, &g.view, g_dev->tiles, &g.indexed, g.rc, *g_dev->grid, g_dev->arch_switch_inf,
                   &g_dev->arch, &g.chan, argv[1], false, "", 0, false, false);
    return 0;
}
#endif
